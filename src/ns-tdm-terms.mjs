// The vocabulary served at /ns/tdm — the definitions behind the `sn:` prefix
// the ODRL representation declares.
//
// WHY: the ODRL policy publishes `"sn": "https://juanlentino.com/ns/tdm#"` and
// then uses terms from it. JSON-LD does not require a namespace URI to
// dereference, so nothing was broken — but the URI was published and returned
// 404, which is a poor look on a site whose entire argument is that claims
// should be machine-checkable. A namespace you publish should resolve.
//
// THE LIST IS AUDITED, NOT MAINTAINED BY HAND. test/ns-tdm.test.mjs walks the
// emitted ODRL document, collects every `sn:` token that actually appears in
// it, and fails if any of them is missing here. That guard exists because the
// obvious way to build this list — grepping the source for "sn:" — MISSES the
// three purpose values, which are generated by interpolation
// (`sn:${token}`) and never appear as literals anywhere. A hand-maintained
// list under-covers silently; the emitted document is the only honest source.

